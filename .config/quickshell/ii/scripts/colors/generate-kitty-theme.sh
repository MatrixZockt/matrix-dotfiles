#!/usr/bin/env bash
# Write kitty's palette for the current shell theme mode, and reload kitty.
#
#   generate-kitty-theme.sh          write the palette for the CURRENT mode
#   generate-kitty-theme.sh dark     force a mode ("dark" | "light")
#
# Called by the shell's MaterialThemeLoader whenever the theme changes, and by
# nothing else. The mode argument is the same single word the other followers
# receive (sync-desktop-theme.sh, custom/theme.lua's hyprctl eval): one
# decision, pushed to every consumer. Run with no argument it reads the mode
# file the shell maintains, so a manual run can never disagree with the shell.
#
# The output is ~/.config/kitty/theme.conf. kitty.conf `include`s it; the
# palette itself lives HERE, in one place, instead of hard-coded in kitty.conf
# where a theme switch could never reach it.
#
# Reload: SIGUSR1 makes kitty re-read its config -- including this file via
# the `include` in kitty.conf -- and repaint RUNNING windows. Verified on this
# desktop: color changes go live on SIGUSR1 (only background_opacity waits for
# new windows, and it does not belong to the theme). Allowed to fail silently:
# no kitty running is not an error for a startup-time call.
kid="$(pidof kitty 2>/dev/null || true)"
if [ -n "$kid" ]; then
    kill -SIGUSR1 $kid 2>/dev/null || true
fi
set -euo pipefail

mode="${1:-}"
mode_file="$HOME/.local/state/quickshell/theme-mode"
if [ -z "$mode" ]; then
    mode="$(cat "$mode_file" 2>/dev/null || true)"
fi
case "$mode" in
    light) ;;
    *) mode="dark" ;;  # anything unrecognised is dark, the desktop's default
esac

out="$HOME/.config/kitty/theme.conf"
mkdir -p "$(dirname "$out")"

if [ "$mode" = "light" ]; then
    cat > "$out" <<'EOF'
# GENERATED by scripts/colors/generate-kitty-theme.sh -- edit that script, or
# better, the shell's theme system, not this file. The light palette: the same
# term0 background and term7 foreground the shell's light template uses, so a
# terminal window and a shell panel are visibly the same surface.
background #CFCFCF
foreground #272022
cursor #272022
cursor_text_color #CFCFCF
selection_background #C6BFC3
selection_foreground #272022
color0  #CFCFCF
color1  #B52755
color2  #A97363
color3  #AF535D
color4  #A67F7C
color5  #B2416B
color6  #8D76AD
color7  #272022
color8  #0E0D0D
color9  #B52755
color10 #A97363
color11 #AF535D
color12 #A67F7C
color13 #B2416B
color14 #8D76AD
color15 #221A1A
EOF
else
    cat > "$out" <<'EOF'
# GENERATED by scripts/colors/generate-kitty-theme.sh -- edit that script, or
# better, the shell's theme system, not this file. The dark palette: the
# terminal-family surface grey the shell itself paints (#141414, the same
# colour Appearance.qml's colTerminalSurfaceSolid uses), near-black ramp ends,
# and the hue accents unchanged from the light ramp so highlighted output keeps
# its colour across a theme switch.
background #141414
foreground #E6E1E1
cursor #E6E1E1
cursor_text_color #141414
selection_background #4A4348
selection_foreground #E6E1E1
color0  #141414
color1  #B52755
color2  #A97363
color3  #AF535D
color4  #A67F7C
color5  #B2416B
color6  #8D76AD
color7  #E6E1E1
color8  #4A4348
color9  #B52755
color10 #A97363
color11 #AF535D
color12 #A67F7C
color13 #B2416B
color14 #8D76AD
color15 #F5EEF0
EOF
fi

# Repaint running windows, then let new ones re-read config (which includes
# this file). Each can fail on its own: no remote-control socket, or no kitty
# at all. `|| true` because a startup call before kitty exists is normal.
kid="$(pidof kitty 2>/dev/null || true)"
if [ -n "$kid" ]; then
    kill -SIGUSR1 $kid 2>/dev/null || true
fi
