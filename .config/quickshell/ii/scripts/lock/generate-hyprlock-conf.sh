#!/usr/bin/env bash
# Generate ~/.config/hypr/hyprlock.conf from the shell's shared login/lock
# template state.
#
# WHY THIS EXISTS
# The settings app writes the chosen layout into Persistent.states.loginLayout
# and runs set-login-layout.sh, which stages a .js fragment for the SDDM LOGIN
# screen. Nothing, however, ever wrote a hyprlock.conf -- so SUPER+L (which
# runs bare `hyprlock`, see modules/common/functions/Session.qml) showed
# hyprlock's BUILT-IN default screen: no wallpaper, no palette, none of the
# layout the settings page was previewing. The one file that did exist was
# hyprlock/colors.conf, a matugen leftover, which hyprlock never even loads
# without a main config.
#
# This script IS the missing link: it renders the shared template -- the same
# LoginLayouts list the lock surface and the settings previews read -- into a
# real hyprlock.conf. It is run by the settings app whenever the layout, the
# lock picture or the theme changes (AppearanceConfig.rebakeLoginTheme), and
# can be run by hand:
#
#   generate-hyprlock-conf.sh              regenerate from current state
#   generate-hyprlock-conf.sh <layout>     regenerate for a specific layout
#
# Wallpaper rules (matching set-lock-wallpaper.sh):
#   * an override set through the settings picker wins
#   * otherwise the DESKTOP wallpaper is used
#
# Theme rules: colours come from the live colors.json (the template system),
# so a dark/light switch regenerating this file carries the new palette onto
# the lock screen.
set -euo pipefail

CONFIG_DIR="${XDG_CONFIG_HOME:-$HOME/.config}"
LOCK_DIR="$CONFIG_DIR/hypr/hyprlock"
OUT="$CONFIG_DIR/hypr/hyprlock.conf"
COLORS_JSON="$HOME/.local/state/quickshell/user/generated/colors.json"
OVERRIDE_FILE="$LOCK_DIR/lock-wallpaper.conf"
LOGIN_LAYOUTS_DIR="$CONFIG_DIR/hypr/custom/sddm-theme/layouts"

LAYOUT="${1:-}"

# ── Layout ────────────────────────────────────────────────────────────────
# The chosen slug lives in the shell's persistent state file. set-login-
# layout.sh already validates slugs against the SDDM fragments; reusing it
# keeps one source of truth for what "a valid layout" means.
CURRENT_LAYOUT="$("$CONFIG_DIR/hypr/custom/scripts/set-login-layout.sh" 2>/dev/null || echo classic)"
if [[ -n "$LAYOUT" ]]; then
    CURRENT_LAYOUT="$LAYOUT"
fi

# ── Wallpaper ─────────────────────────────────────────────────────────────
wallpaper=""
if [[ -f "$OVERRIDE_FILE" ]]; then
    wallpaper="$(sed -n 's/^[[:space:]]*\$background_image[[:space:]]*=[[:space:]]*//p' "$OVERRIDE_FILE" | tail -n 1)"
fi
if [[ -z "$wallpaper" ]]; then
    # Fall back to the desktop wallpaper: first path in the shell's history
    # file (a plain JSON array, newest first), then matugen's record, then
    # nothing.
    wallpaper="$(python3 - "$HOME/.local/state/quickshell/wallpaper-history.json" <<'PY' 2>/dev/null || true
import json, sys
try:
    d = json.load(open(sys.argv[1]))
    w = d if isinstance(d, list) else (d.get("wallpapers") or [])
    if w: print(w[0])
except Exception:
    pass
PY
)"
fi
if [[ -z "$wallpaper" ]]; then
    wallpaper="$(sed -n 's/^[[:space:]]*\$background_image[[:space:]]*=[[:space:]]*//p' "$LOCK_DIR/colors.conf" 2>/dev/null | tail -n 1)"
fi

# ── Palette ───────────────────────────────────────────────────────────────
# Read straight from the live template so a theme switch only needs a
# regeneration, not a new palette pipeline.
read -r BG ONBG PRIMARY OUTLINE ERROR DIM < <(python3 - "$COLORS_JSON" <<'PY' 2>/dev/null || true
import json, sys
try:
    d = json.load(open(sys.argv[1]))
    print(d.get("background","#131313"), d.get("onBackground","#E2E2E2"),
          d.get("primary","#F0F0F0"), d.get("outlineVariant","#474747"),
          d.get("error","#B52755"), d.get("scrim","#000000"))
except Exception:
    print("#131313 #E2E2E2 #F0F0F0 #474747 #B52755 #000000")
PY
)
BG="${BG:-#131313}"; ONBG="${ONBG:-#E2E2E2}"; PRIMARY="${PRIMARY:-#F0F0F0}"
OUTLINE="${OUTLINE:-#474747}"; ERROR="${ERROR:-#B52755}"; DIM="${DIM:-#000000}"

hex2rgba() {  # #RRGGBB -> rgba(rrggbbAA)
    printf 'rgba(%s%s)' "${1#'#'}" "$2"
}

FILL=$(hex2rgba "$BG" "F0")          # entry surface
RING=$(hex2rgba "$OUTLINE" "88")     # entry border
TEXT=$(hex2rgba "$ONBG" "FF")
ACCENT=$(hex2rgba "$PRIMARY" "FF")
ERR=$(hex2rgba "$ERROR" "FF")
DIMC=$(hex2rgba "$DIM" "FF")       # solid background
HALO=$(hex2rgba "$DIM" "66")         # photo scrim
# hyprlock parses through Hyprland's config reader, where '#' starts a
# COMMENT -- a bare `color = #000000` reads as `color =` and fails with
# "cannot parse \"\" as an int". Every colour in this file must therefore be
# in rgba() form, never bare hex.

FONT="${FONT:-Google Sans Flex Medium}"
SYMBOLS="${SYMBOLS:-Material Symbols Rounded}"

mkdir -p "$LOCK_DIR"
TMP="$OUT.tmp"
{
    echo "# Generated by scripts/lock/generate-hyprlock-conf.sh — DO NOT EDIT."
    echo "# Source: the shell's login/lock template state (LoginLayouts)."
    echo "# Layout: $CURRENT_LAYOUT"
    echo
    echo "source = $LOCK_DIR/colors.conf"
    echo
    echo "general {"
    echo "    hide_cursor = true"
    echo "    ignore_empty_input = true"
    echo "}"
    echo
    echo "# ── Background ──"
    # NOTE: `monitor =` (empty) is a parse error on this hyprlock (0.9.6:
    # "cannot parse \"\" as an int") -- the key is simply omitted, which is
    # how an all-monitors background is spelled here.
    if [[ -n "$wallpaper" && -f "${wallpaper//\"/}" ]]; then
        echo "background {"
        echo "    path = $wallpaper"
        echo "    color = $DIMC"
        echo "    blur_passes = 0"
        echo "}"
        echo
        echo "# Reading scrim so white text survives a bright photo."
        echo "shape {"
        echo "    size = 100%, 100%"
        echo "    color = $HALO"
        echo "    rounding = 0"
        echo "}"
    else
        echo "background {"
        echo "    color = $DIMC"
        echo "}"
    fi
    echo
    echo "# ── Clock ──"
    echo "label {"
    echo "    text = cmd[update:1000] echo \"\$(date +'%H:%M')\""
    echo "    font_size = 120"
    echo "    font_family = $FONT"
    echo "    color = $TEXT"
    echo "    position = 0%, 22%"
    echo "    halign = center"
    echo "    valign = center"
    echo "}"
    echo "label {"
    echo "    text = cmd[update:10000] echo \"\$(date +'%A, %d %B')\""
    echo "    font_size = 22"
    echo "    font_family = $FONT"
    echo "    color = $TEXT"
    echo "    position = 0%, 30%"
    echo "    halign = center"
    echo "    valign = center"
    echo "}"
    echo
    echo "# ── Auth ──"
    echo "input-field {"
    echo "    size = 360, 56"
    echo "    outline_thickness = 2"
    echo "    dots_size = 0.25"
    echo "    dots_spacing = 0.3"
    echo "    dots_center = true"
    echo "    placeholder_text = <i>Type your password</i>"
    echo "    fail_text = <i>Wrong password</i>"
    echo "    fail_color = $ERR"
    echo "    check_color = $ACCENT"
    echo "    bothlock_color = $ERR"
    echo "    capslock_color = $ERR"
    echo "    numlock_color = $ACCENT"
    echo "    font_family = $FONT"
    echo "    position = 0%, -12%"
    echo "    halign = center"
    echo "    valign = center"
    echo "}"
} > "$TMP"
mv "$TMP" "$OUT"
echo "hyprlock.conf written: $OUT (layout $CURRENT_LAYOUT)"
